"""Evaluation harness (MVP plan milestone M9).

Runs the sample set through ``rule_only``, ``llm_only`` and ``hybrid`` and writes
``eval/report.md`` and ``eval/results.csv`` with QWK (primary), MAE, exact and
adjacent agreement, bootstrap confidence intervals, a grade-band confusion
matrix, explanation faithfulness, latency/token cost and a fairness probe.

Run with: ``python -m eval.run_eval`` (or ``make eval``).
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

# Make ``ees`` importable when running directly from a checkout.
SRC = Path(__file__).resolve().parents[1] / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from ees import explainer  # noqa: E402
from ees.config import PROJECT_ROOT, load_config  # noqa: E402
from ees.data_io import load_sample_essays  # noqa: E402
from ees.grading import grade_for  # noqa: E402
from ees.kb_loader import load_knowledge  # noqa: E402
from ees.llm_gateway import LLMGateway  # noqa: E402
from ees.metrics import (  # noqa: E402
    adjacent_agreement,
    bootstrap_ci,
    exact_agreement,
    mae,
    quadratic_weighted_kappa,
)
from ees.pipeline import mark  # noqa: E402

CRITERIA = ["content", "organization", "language", "mechanics"]
MODES = ["rule_only", "llm_only", "hybrid"]
MAX_TOTAL = 40
GRADE_LETTERS = ["F", "E", "D", "C", "B", "A"]


def _grade_index(total: float) -> int:
    return GRADE_LETTERS.index(grade_for(total, MAX_TOTAL))


def run() -> pd.DataFrame:
    config = load_config()
    kb = load_knowledge(config.kb_path)
    if not config.llm.api_key:
        raise SystemExit(
            f"provider '{config.llm.provider}' requires {config.llm.api_key_env}"
        )
    gateway = LLMGateway(
        provider=config.llm.provider,
        model=config.llm.model,
        api_key=config.llm.api_key,
        base_url=config.llm.base_url,
    )
    essays = load_sample_essays(config)
    runs_dir = config.runs_path
    runs_dir.mkdir(parents=True, exist_ok=True)

    rows: list[dict] = []
    latencies: dict[str, list[float]] = {m: [] for m in MODES}
    tokens: dict[str, int] = {m: 0 for m in MODES}
    faithfulness: dict[str, list[bool]] = {m: [] for m in MODES}

    for essay in essays:
        for mode in MODES:
            t0 = time.perf_counter()
            result = mark(
                essay.text, kb, config, gateway, mode=mode, prompt_id=essay.prompt_id
            )
            latency = time.perf_counter() - t0
            latencies[mode].append(latency)
            tokens[mode] += result.tokens

            if result.firing_log:
                ok, _ = explainer.verify_feedback(result.feedback, result.firing_log)
            else:
                ok = True
            faithfulness[mode].append(ok)

            (runs_dir / f"{essay.essay_id}_{mode}.json").write_text(
                result.model_dump_json(indent=2), encoding="utf-8"
            )

            row = {
                "essay_id": essay.essay_id,
                "prompt_id": essay.prompt_id,
                "quality": essay.quality,
                "mode": mode,
                "pred_total": result.total,
                "gold_total": essay.adjudicated_total,
                "grade": result.grade,
                "flagged": bool(result.flags),
                "n_flags": len(result.flags),
                "latency_s": round(latency, 4),
                "tokens": result.tokens,
            }
            for crit in CRITERIA:
                cs = next((s for s in result.criterion_scores if s.criterion == crit), None)
                row[f"pred_{crit}"] = cs.score if cs else 0.0
                row[f"gold_{crit}"] = essay.criterion_scores.get(crit, 0.0)
            rows.append(row)

    df = pd.DataFrame(rows)
    df.to_csv(PROJECT_ROOT / "eval" / "results.csv", index=False)
    _write_report(df, essays, latencies, tokens, faithfulness)
    return df


def _write_report(df, essays, latencies, tokens, faithfulness) -> None:
    gold = [e.adjudicated_total for e in essays]
    h1 = [e.human_totals[0] for e in essays]
    h2 = [e.human_totals[1] for e in essays]

    lines: list[str] = []
    lines.append("# Evaluation Report\n")
    lines.append(
        "Generated by `python -m eval.run_eval` on the sample set in the repo. "
        f"{len(essays)} essays; modes: {', '.join(MODES)}.\n"
    )
    lines.append(
        "> Indicative only: the sample set is small. The real evaluation requires "
        "a larger, locally collected dataset (see `docs/research_mapping.md`).\n"
    )

    # Human ceiling
    lines.append("## Human inter-rater agreement (ceiling reference)\n")
    lines.append(
        f"- QWK(human1, human2) = "
        f"{quadratic_weighted_kappa(h1, h2, 0, MAX_TOTAL):.3f}"
    )
    lines.append(
        f"- MAE(human1, human2) = {mae(h1, h2):.3f}; "
        f"exact = {exact_agreement(h1, h2):.3f}; "
        f"adjacent = {adjacent_agreement(h1, h2):.3f}\n"
    )

    # Overall table
    lines.append("## Overall agreement with human adjudicated marks\n")
    lines.append("| Mode | QWK (95% CI) | MAE | Exact | Adjacent | Faithfulness | Median latency (s) | Tokens |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for mode in MODES:
        sub = df[df["mode"] == mode]
        pred = sub["pred_total"].tolist()
        q = quadratic_weighted_kappa(gold, pred, 0, MAX_TOTAL)
        lo, hi = bootstrap_ci(quadratic_weighted_kappa, gold, pred, n_boot=1000)
        faith = float(np.mean(faithfulness[mode])) if faithfulness[mode] else float("nan")
        lines.append(
            f"| {mode} | {q:.3f} [{lo:.3f}, {hi:.3f}] | {mae(gold, pred):.3f} | "
            f"{exact_agreement(gold, pred):.3f} | {adjacent_agreement(gold, pred):.3f} | "
            f"{faith:.2f} | {np.median(latencies[mode]):.3f} | {tokens[mode]} |"
        )
    lines.append("")

    # Per-criterion QWK
    lines.append("## Per-criterion QWK (0-10 scale)\n")
    header = "| Criterion | " + " | ".join(MODES) + " |"
    lines.append(header)
    lines.append("|---|" + "---|" * len(MODES))
    for crit in CRITERIA:
        gold_c = [e.criterion_scores.get(crit, 0.0) for e in essays]
        cells = []
        for mode in MODES:
            sub = df[df["mode"] == mode]
            pred_c = sub[f"pred_{crit}"].tolist()
            cells.append(f"{quadratic_weighted_kappa(gold_c, pred_c, 0, 10):.3f}")
        lines.append(f"| {crit} | " + " | ".join(cells) + " |")
    lines.append("")

    # Grade-band confusion (hybrid)
    lines.append("## Grade-band confusion matrix (hybrid; rows=human, cols=system)\n")
    sub = df[df["mode"] == "hybrid"]
    mat = np.zeros((6, 6), dtype=int)
    for _, r in sub.iterrows():
        mat[_grade_index(r["gold_total"]), _grade_index(r["pred_total"])] += 1
    lines.append("| human \\ system | " + " | ".join(GRADE_LETTERS) + " |")
    lines.append("|---|" + "---|" * 6)
    for i, letter in enumerate(GRADE_LETTERS):
        lines.append(f"| {letter} | " + " | ".join(str(v) for v in mat[i]) + " |")
    lines.append("")

    # Fairness probe
    lines.append("## Fairness probe: mean predicted total by essay-length band (hybrid)\n")
    sub = df[df["mode"] == "hybrid"].copy()
    lengths = []
    for _, r in sub.iterrows():
        text = next(e.text for e in essays if e.essay_id == r["essay_id"])
        lengths.append(len(text.split()))
    sub["words"] = lengths
    bands = pd.cut(sub["words"], bins=[0, 100, 160, 10000], labels=["short", "medium", "long"])
    probe = sub.groupby(bands, observed=True)["pred_total"].agg(["count", "mean"]).round(2)
    lines.append(probe.to_markdown())
    lines.append("")

    # Flagged cases
    lines.append("## Flagged cases (hybrid)\n")
    flagged = sub[sub["n_flags"] > 0][["essay_id", "gold_total", "pred_total", "n_flags"]]
    if flagged.empty:
        lines.append("_No flagged cases._\n")
    else:
        lines.append(flagged.to_markdown(index=False))
        lines.append("")

    lines.append(
        "## Notes\n"
        "- All modes call the live provider; `rule_only` uses only deterministic "
        "NLP facts and never calls the LLM.\n"
        "- QWK uses the 0-40 mark scale overall and 0-10 per criterion.\n"
        "- Faithfulness = fraction of essays whose feedback cites only fired rules.\n"
    )

    path = PROJECT_ROOT / "eval" / "report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {path} and eval/results.csv")


if __name__ == "__main__":
    run()
